     */
    public function edit($id)
    {
        $data['unity'] = Unity::find($id);
        return view('admin.unity-edit', $data);
    }

    /**
     * Update the specified resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {
        $unity = Unity::find($id);
        $unity->name = $request->input('name');
        $unity->save();

        \Session::flash('status', ' تعديل الوحدة بالنظام');

        return back();
    }

